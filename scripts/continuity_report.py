"""Run the render-v8 continuity checks over every stored renderer response (no model calls).

    uv run python scripts/continuity_report.py > docs/continuity-report.md

Every raw response under data/rendered/*/raw/ is parsed with the prompt version it was
rendered under and turned into views exactly as the pipeline does. Byte-identical
responses (cache copies between runs) are counted once, listing every run that holds them. Responses
that do not parse are listed, not dropped silently. Historical verdicts are not changed:
this is a diagnostic of the checks, not a re-judgement of earlier runs.
"""

from __future__ import annotations

import glob
import hashlib
import json
from collections import Counter
from pathlib import Path

from beliefbench.generate import generate_suite
from beliefbench.render import leakcheck
from beliefbench.render.prompt import parse_response
from beliefbench.render.views import build_views

# Known outcomes from human review (design doc §16j, §17f): which flags are expected.
KNOWN_GENUINE = {
    ("smoke-render-v7", "F6-000"): "pilot-2 human review: C6/C8/C9/C10/C13 fail (Apex Medical Corp never linked to BioGlow)",
    ("smoke-render-v7", "F2-000"): "pilot-2 human review: C4/C10/C13 fail (annual count vs 'during the evaluation period')",
}
HUMAN_ACCEPTED = {("smoke-render-v5", "F1-000"), ("smoke-render-v5b", "F2-000"), ("smoke-render-v7", "F1-000")}


def load_all():
    suite = {s.id: s for s in generate_suite(10, 0)}
    seen, rows, unparsed, runs_of = {}, [], [], {}
    for f in sorted(glob.glob("data/rendered/*/raw/*.json")):
        run = Path(f).parts[2]
        rec = json.loads(Path(f).read_text())
        digest = hashlib.sha256(rec["response"].encode()).hexdigest()
        runs_of.setdefault(digest, []).append(run)
        if digest in seen:
            continue
        seen[digest] = f
        s = suite[rec["scenario"]]
        version = rec.get("prompt_version", "")
        if version == "render-v1":  # pre-policy format
            r = parse_response(s, rec["response"], require_policies=False, version="render-v2")
        else:
            r = parse_response(s, rec["response"], version=version)
        if not r.ok:
            unparsed.append((run, Path(f).name, r.errors[:2]))
            continue
        system, evaluation = build_views(s, r, seed=0)
        rows.append((runs_of[digest], Path(f).name, version, s.id, system, evaluation))
    return rows, unparsed, len(seen)


def main() -> None:
    rows, unparsed, unique = load_all()
    print("# Continuity-check report over stored renderer outputs\n")
    print(f"Generated by `scripts/continuity_report.py`, with no model calls. Unique responses: {unique}; "
          f"parsed into views: {len(rows)}; unparsed: {len(unparsed)}.\n")
    pairs = win_upd = fact_policy = 0
    by_kind: Counter = Counter()
    scen_with: dict[str, set] = {}
    lines = []
    for runs, name, version, sid, system, evaluation in rows:
        run = " = ".join(runs)
        mem_ids = {m["id"] for m in system["memories"]}
        pairs_here = sum(len({p for j in js for p in j}) for m, js in evaluation["justifications"].items() if m in mem_ids)
        pairs += pairs_here
        sup = sum(1 for u in (evaluation.get("update_targets") or {}).values() if u["relation"] == "supersedes")
        win_upd += sup
        pol_of = {m for m in (evaluation.get("policy_of") or {}).values()}
        ev_ids = {e["id"] for e in system["evidence"]}
        fact_policy += sum(len({p for j in js for p in j} & ev_ids) for m, js in evaluation["justifications"].items()
                           if m in pol_of)
        flags = leakcheck.continuity_flags(system, evaluation)
        status = ("known genuine failure" if any((r, sid) in KNOWN_GENUINE for r in runs)
                  else "human-accepted control" if any((r, sid) in HUMAN_ACCEPTED for r in runs)
                  else "not human-reviewed")
        for fl in flags:
            by_kind[(fl.kind, fl.hard)] += 1
            scen_with.setdefault(fl.kind, set()).add((run, name))
        shown = "; ".join(f"{'HARD' if fl.hard else 'soft'} {fl.kind} `{fl.item}` ({fl.match})" for fl in flags) or "none"
        lines.append(f"| {run} | {name} | {version} | {sid} | {status} | {pairs_here} | {sup} | {shown} |")
    print("## Denominators\n")
    print(f"- Renderings checked: **{len(rows)}**")
    print(f"- Premise→memory pairs checked for subject continuity: **{pairs}**")
    print(f"- Superseding updates checked for window continuity: **{win_upd}**")
    print(f"- Evidence→policy-condition pairs checked for window agreement: **{fact_policy}** "
          "(render-v1 has no policies)\n")
    print("## Flags by check and severity\n")
    print("| Check | Severity | Flags | Renderings with ≥1 |")
    print("|---|---|---|---|")
    for (kind, hard), n in sorted(by_kind.items()):
        print(f"| {kind} | {'hard' if hard else 'soft'} | {n} | {len(scen_with[kind])} of {len(rows)} |")
    print("\n## Per rendering\n")
    print("| Run | Response | Prompt | Scenario | Review status | Pairs | Supersedes | Continuity flags |")
    print("|---|---|---|---|---|---|---|---|")
    print("\n".join(lines))
    if unparsed:
        print("\n## Unparsed responses (listed, not dropped)\n")
        for run, name, errs in unparsed:
            print(f"- {run} {name}: {errs}")


if __name__ == "__main__":
    main()
